def build_name_map(quotes: Dict[str, dict]) -> Dict[str, str]:
    """由腾讯快照返回 {code: name}。"""
    return {c: (q.get("name") or c) for c, q in quotes.items()}


def _load_code_sector() -> Dict[str, str]:
    """从 watchlist_data.js 解析 code -> sector 映射（脚本生成，单一真源）。"""
    path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "watchlist_data.js")
    mapping: Dict[str, str] = {}
    try:
        raw = open(path, "r", encoding="utf-8").read()
        for m in re.finditer(r'"code":\s*"(\d+)".*?"sector":\s*"([^"]*)"', raw, re.S):
            mapping[m.group(1)] = m.group(2)
    except Exception:
        pass
    return mapping


