def get_code_sector() -> Dict[str, str]:
    global _CODE_SECTOR_CACHE
    if not _CODE_SECTOR_CACHE:
        _CODE_SECTOR_CACHE = _load_code_sector()
    return _CODE_SECTOR_CACHE


